# Writes db/migrations/012_seed_games.sql: the shop catalog = luduscore's games plus tools/extra_games.json,
# keeping only games with a verified physical price in tools/catalog_prices.json.
# Build-time tooling (like db/migrate.js), not app code: the app only ever reads the generated SQL.
# Setup once, from launch-rush/: python -m venv .venv ; .venv\Scripts\python.exe -m pip install -r tools/requirements.txt
# Run once: .venv\Scripts\python.exe tools/export_catalog.py  (then: npm run migrate)
# Refuses to overwrite: an applied migration must not change (db/migrate.js checksum); change the catalog with a new migration.
import hashlib
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import luduscore
from luduscore import ScoringEngine

TOOLS = Path(__file__).parent
OUT = TOOLS.parent / "db" / "migrations" / "012_seed_games.sql"


def load(name, **options):
    return json.loads((TOOLS / name).read_text(encoding="utf-8"), **options)


def demo_price_minor(usd, rate):
    # usd x rate, rounded to the nearest 100 INR, returned in paise (design §4: integer minor units).
    rupees = (usd * rate / 100).quantize(Decimal("1"), rounding=ROUND_HALF_UP) * 100
    return int(rupees * 100)


def starting_stock(game_id):
    # 100, 150, ... 500, fixed per game: derived from the id, so a re-run gives the same number.
    return 100 + (int(hashlib.sha256(game_id.encode()).hexdigest(), 16) % 9) * 50


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


extra = load("extra_games.json")["games"]
price_file = load("catalog_prices.json", parse_float=Decimal)  # exact decimals, never binary floats
prices, rate = price_file["prices"], Decimal(price_file["usd_to_inr"])

games = ScoringEngine(extra_games=extra).games  # the library validates keys and rejects duplicate ids
unknown = set(prices) - {g["id"] for g in games}
if unknown:
    raise SystemExit(f"catalog_prices.json has ids not in the catalog: {sorted(unknown)}")

rows = [
    f"  ({sql_text(g['id'])}, {sql_text(g['title'])}, {demo_price_minor(prices[g['id']]['usd'], rate)}, 'INR', "
    f"{starting_stock(g['id'])}, true)"
    for g in games
    if g["id"] in prices
]

sql = (
    f"-- Shop catalog: {len(rows)} games. Generated by tools/export_catalog.py from luduscore {luduscore.__version__}\n"
    "-- plus tools/extra_games.json, priced from tools/catalog_prices.json (sources there). Do not edit by hand.\n"
    "INSERT INTO games (id, title, price_minor, currency, stock_total, listed_in_shop) VALUES\n"
    + ",\n".join(rows)
    + ";\n"
)
with OUT.open("x", encoding="utf-8", newline="\n") as f:  # "x": fails if the file already exists
    f.write(sql)
print(f"wrote {OUT.name}: {len(rows)} games")
